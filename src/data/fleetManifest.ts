export const FLEET_MANIFEST = fleetManifest;

export function getHangarUnits(): FleetUnit[] {
  return [...fleetManifest].sort((a, b) => a.slot - b.slot);
}

export function getFleetUnitById(id: string): FleetUnit | undefined {
  return fleetManifest.find((unit) => unit.id === id);
}
