const HIRED_HUD_CHAT_TARGET_POOL = 50;

/** ~50 unique reply seeds per hired bay — problems, glam, young voice. */
export function getDeveloperChatReplyPool(slot: number): readonly string[] {
  const slotLines = HIRED_HUD_DEVELOPER_CHAT_SLOT_REPLIES[slot] ?? [];
  const merged = [...new Set([...slotLines, ...HIRED_HUD_DEVELOPER_CHAT_SHARED_PROBLEMS])];
  if (merged.length >= HIRED_HUD_CHAT_TARGET_POOL) {
    return merged.slice(0, HIRED_HUD_CHAT_TARGET_POOL);
  }
  const padded = [...merged];
  let index = 0;
  while (padded.length < HIRED_HUD_CHAT_TARGET_POOL) {
    padded.push(HIRED_HUD_DEVELOPER_CHAT_SHARED_PROBLEMS[index % HIRED_HUD_DEVELOPER_CHAT_SHARED_PROBLEMS.length]);
    index += 1;
  }
  return padded;
}

export function pickDeveloperChatReply(
  slot: number,
  recent: ReadonlySet<string>,
  rng: () => number = Math.random,
): string {
  const pool = getDeveloperChatReplyPool(slot);
  const untouched = pool.filter((line) => !recent.has(line));
  const source = untouched.length > 0 ? untouched : pool;
  return source[Math.floor(rng() * source.length)] ?? pool[0] ?? "I'm on your line — ask me again.";
}
