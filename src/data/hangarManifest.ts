export const hangarManifest: FleetUnit[] = HANGAR_MANIFEST_CORE.map((unit) => ({
  ...unit,
  callName: unit.name.trim(),
  systemPrompt: buildUnitSystemPrompt(unit),
}));

export const HANGAR_MANIFEST = hangarManifest;

export function getHangarUnits(): FleetUnit[] {
  return [...hangarManifest].sort((a, b) => a.slot - b.slot);
}

export function getHangarUnitById(id: string): FleetUnit | undefined {
  return hangarManifest.find((unit) => unit.id === id);
}

export function getHangarUnitByCallName(callName: string): FleetUnit | undefined {
  const normalized = callName.trim().toLowerCase();
  if (!normalized) return undefined;
  return hangarManifest.find((unit) => unit.callName.trim().toLowerCase() === normalized);
}

export function verifyHangarCallName(callName: string): boolean {
  return Boolean(getHangarUnitByCallName(callName));
}
